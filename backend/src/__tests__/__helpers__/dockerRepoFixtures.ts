function packet(tag: number, body: Buffer): Buffer {
  if (body.length >= 192) throw new Error('fixture packets stay short');
  return Buffer.concat([Buffer.from([0xc0 | tag, body.length]), body]);
}

/** A well-formed v4 public-key packet for a key that is not Docker's. */
export function unrelatedKeyBinary(seed = 'unrelated'): Buffer {
  const material = crypto.createHash('sha256').update(seed).digest();
  const body = Buffer.concat([Buffer.from([4, 0, 0, 0, 1, 1, 0, 8]), material]);
  return packet(6, body);
}

export function armor(bytes: Buffer): string {
  const lines = bytes.toString('base64').match(/.{1,64}/g) ?? [];
  return ['-----BEGIN PGP PUBLIC KEY BLOCK-----', '', ...lines, '=AAAA', '-----END PGP PUBLIC KEY BLOCK-----', ''].join('\n');
}

/** The `docker_repo` probe's block for one keyring file. */
export function keyBlock(path: string, bytes: Buffer, size = bytes.length): string {
  return [
    `KEY_BEGIN=${path}`,
    `KEY_SIZE=${size}`,
    bytes.toString('base64'),
    `KEY_END=${path}`,
  ].join('\n');
}

